import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const SOURCE = fileURLToPath(new URL("../design/system/tokens.json", import.meta.url));
const TARGET = fileURLToPath(new URL("../design/system/tokens.css", import.meta.url));

const formatComment = (usage) => (usage === undefined ? "" : `  /* ${usage.replaceAll("*/", "* /")} */`);

export const buildTokensCss = (tokens) => {
  const colors = tokens.color.tokens.map(
    (token) => `  --color-${token.name}: ${token.value};${formatComment(token.usage)}`,
  );
  const families = Object.entries(tokens.type.families).map(([name, value]) => `  --font-${name}: ${value};`);
  const styles = tokens.type.styles.flatMap((style) => [
    `  --text-${style.name}: ${style.fontSize};${formatComment(style.usage)}`,
    `  --text-${style.name}--line-height: ${style.lineHeight};`,
  ]);
  const radii = tokens.radius.tokens.map(
    (token) => `  --radius-${token.name}: ${token.value};${formatComment(token.usage)}`,
  );
  const layout = tokens.layout.tokens.map(
    (token) => `  --${token.type}-${token.name}: ${token.value};${formatComment(token.usage)}`,
  );

  return [
    "/* Generated by scripts/build-design-tokens.mjs from tokens.json. Do not edit by hand. */",
    "",
    "/* Each family is reset first, so only the design system's names exist as classes. */",
    "@theme {",
    "  --color-*: initial;",
    "  --text-*: initial;",
    "  --radius-*: initial;",
    "",
    ...colors,
    "  --color-transparent: transparent;",
    "",
    ...families,
    "",
    ...styles,
    "",
    ...radii,
    "",
    ...layout,
    "}",
    "",
  ].join("\n");
};

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const tokens = JSON.parse(readFileSync(SOURCE, "utf8"));
  writeFileSync(TARGET, buildTokensCss(tokens));
}
