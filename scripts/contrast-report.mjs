import { ContrastUtil } from "../src/Utils/ContrastUtil.ts";

// Why: WCAG 2.2 thresholds per role; text is 4.5:1, large text, control borders and focus rings 3:1; a decorative or disabled pair is listed and never fails.
export const THRESHOLD_BY_ROLE = {
  text: 4.5,
  "large-text": 3,
  ui: 3,
  decorative: undefined,
  disabled: undefined,
};
const RATIO_DECIMALS = 2;
const DECIMAL_BASE = 10;
const ROUNDING = DECIMAL_BASE ** RATIO_DECIMALS;

const readColorValue = (nameToValue, name) => {
  // Why: a pair names tokens, so a token that is renamed or removed fails here with its name, not as a silent pass.
  if (!nameToValue.has(name)) {
    throw new Error(`contrast: no color token named "${name}" in tokens.json`);
  }
  return nameToValue.get(name);
};

const measurePair = (nameToValue, pair) => {
  const background = ContrastUtil.parseColor(readColorValue(nameToValue, pair.background)).rgb;
  const foregroundColor = ContrastUtil.parseColor(readColorValue(nameToValue, pair.foreground));
  const foreground = ContrastUtil.resolveComposite(foregroundColor, background);
  return ContrastUtil.resolveContrastRatio(foreground, background);
};

export const buildContrastRows = ({ tokens, pairs }) => {
  const nameToValue = new Map(tokens.color.tokens.map((token) => [token.name, token.value]));
  return pairs.map((pair) => {
    if (!(pair.role in THRESHOLD_BY_ROLE)) {
      throw new Error(`contrast: unknown role "${pair.role}" for ${pair.foreground} on ${pair.background}`);
    }
    const ratio = measurePair(nameToValue, pair);
    const threshold = THRESHOLD_BY_ROLE[pair.role];
    return {
      ...pair,
      ratio: Math.round(ratio * ROUNDING) / ROUNDING,
      threshold,
      passes: threshold === undefined || ratio >= threshold,
    };
  });
};

export const findFailingRows = (rows) => rows.filter((row) => !row.passes);

const TABLE_HEADER = [
  "| Foreground | Background | Role | Ratio | Threshold | Result | Used for |",
  "| --- | --- | --- | --- | --- | --- | --- |",
];

const formatRow = (row) => {
  const threshold = row.threshold === undefined ? "none" : `${row.threshold}:1`;
  const result = row.passes ? "pass" : "fail";
  const ratio = `${row.ratio.toFixed(RATIO_DECIMALS)}:1`;
  return `| \`${row.foreground}\` | \`${row.background}\` | ${row.role} | ${ratio} | ${threshold} | ${result} | ${row.uses} |`;
};

export const buildContrastMarkdown = (rows) => {
  // Why: generated by pnpm design:tokens, so the table is the computed ratio of each pair and cannot drift from the tokens.
  return [
    "# Contrast of the color pairs",
    "",
    "Generated by `pnpm design:tokens` from `tokens.json` and `contrast-pairs.json`. Do not edit by hand.",
    "",
    ...TABLE_HEADER,
    ...rows.map(formatRow),
    "",
  ].join("\n");
};
